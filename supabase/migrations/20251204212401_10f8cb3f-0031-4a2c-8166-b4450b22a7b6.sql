-- Create custom_programs table
CREATE TABLE public.custom_programs (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  name TEXT NOT NULL,
  description TEXT,
  days_per_week INTEGER DEFAULT 3,
  created_at TIMESTAMPTZ DEFAULT now()
);

-- Create custom_program_workouts table
CREATE TABLE public.custom_program_workouts (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  program_id UUID REFERENCES public.custom_programs(id) ON DELETE CASCADE NOT NULL,
  title TEXT NOT NULL,
  description TEXT,
  day_label TEXT,
  exercises JSONB NOT NULL DEFAULT '[]',
  sort_order INTEGER DEFAULT 0,
  created_at TIMESTAMPTZ DEFAULT now()
);

-- Enable RLS
ALTER TABLE public.custom_programs ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.custom_program_workouts ENABLE ROW LEVEL SECURITY;

-- RLS policies
CREATE POLICY "Allow all access to custom_programs" ON public.custom_programs FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow all access to custom_program_workouts" ON public.custom_program_workouts FOR ALL USING (true) WITH CHECK (true);

